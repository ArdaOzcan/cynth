float
wave_custom(float t)
{
    return 1.0f * cynth_triangle_normalized(t * 1.0f / 1.0f) +
           0.263f * cynth_triangle_normalized(t * 1.998f / 1.0f) +
           0.14f * cynth_triangle_normalized(t * 3.0f / 1.0f) +
           0.099f * cynth_triangle_normalized(t * 4.01f / 1.0f) +
           0.209f * cynth_triangle_normalized(t * 5.02f / 1.0f) +
           0.02f * cynth_triangle_normalized(t * 6.05f / 1.0f) +
           0.029f * cynth_triangle_normalized(t * 7.07f / 1.0f) +
           0.077f * cynth_triangle_normalized(t * 8.12f / 1.0f) +
           0.017f * cynth_triangle_normalized(t * 9.18f / 1.0f) +
           0.01f * cynth_triangle_normalized(t * 10.25f / 1.0f);
}

static inline int16_t
clamp_i16(int32_t val, int16_t min, int16_t max)
{
    if (val < min)
        return min;
    if (val > max)
        return max;
    return val;
}

void
cynth_filter_delay(const CynthBuffer* buffer, float offset_as_sec, float volume)
{
    int frame              = 0;
    size_t offset_as_frame = offset_as_sec * buffer->ss.rate;
    for (frame = buffer->frame_amount - offset_as_frame; frame > 0; --frame) {
        int16_t* left  = &buffer->data[frame * 2 + offset_as_frame];
        int16_t* right = &buffer->data[frame * 2 + offset_as_frame + 1];

        int32_t added_sample_l = volume * buffer->data[frame * 2];
        int32_t added_sample_r = volume * buffer->data[frame * 2 + 1];
        int32_t new_sample_l =
          clamp_i16(*left + added_sample_l, INT16_MIN, INT16_MAX);
        int32_t new_sample_r =
          clamp_i16(*right + added_sample_r, INT16_MIN, INT16_MAX);

        *left  = new_sample_l;
        *right = new_sample_r;
    }
}

#define byte_reader_read(reader, T)                                            \
    ((reader)->offset += sizeof(T), *(T*)(&((reader)->data[(reader)->offset])))

typedef struct
{
    const uint8_t* data;
    size_t offset;
    size_t size;
} ByteReader;

ByteReader
byte_reader_init(const void* data, size_t length)
{
    return (ByteReader){ .data = data, .offset = 0, .size = length };
}

int
main(void)
{
    CynthEngine* engine;
    CynthSampleSpec ss;

    ss.format   = PA_SAMPLE_S16NE;
    ss.channels = 2;
    ss.rate     = 44100;

    engine = cynth_engine_init(&ss, "default");

    VArena varena = { 0 };
    varena_init(&varena, 1 << 26);
    Allocator alloc       = varena_allocator(&varena);
    float buffer_duration = 200.0f;
    int16_t* data =
      make(int16_t, buffer_duration* ss.rate* ss.channels, &alloc);

    CynthBuffer buffer = { 0 };
    cynth_buffer_init(&buffer, ss, buffer_duration, data);

    CynthEnvelope env = {
        .attack = 0.0125f, .decay = 1.0f, .sustain = 0.5f, .release = 0.5f
    };

    // CynthNote note = {
    //     .frequency = CYNTH_FREQ_G,
    //     .start_time = 0.1f,
    //     .duration = 1.0f,
    //     .volume = 1.0f,
    // };
    //
    // cynth_buffer_add_wave(&buffer,
    //                        env,
    //                        note.start_time * buffer.ss.rate,
    //                        note.duration * buffer.ss.rate,
    //                        cynth_sine_normalized,
    //                        note.frequency,
    //                        note.volume);
    //
    cynth_buffer_write_notes(&buffer,
                             notes_pink_panther,
                             sizeof(notes_pink_panther) /
                               sizeof(*notes_pink_panther),
                             env,
                             wave_custom);
    cynth_filter_delay(&buffer, 0.5f, 0.25f);
    cynth_filter_delay(&buffer, 1.0f, 0.125f);
    cynth_filter_delay(&buffer, 1.5f, 0.025f);
    cynth_filter_delay(&buffer, 2.0f, 0.0125f);

    // cynth_buffer_fprint(&buffer, stdout);

    int export_res = cynth_buffer_export_wav(&buffer, "out/out.wav");
    if (export_res != 0) {
        fprintf(stderr, "File out.wav could not be opened.");
        cynth_engine_deinit(engine);
        return 1;
    }

    size_t loop      = 1;
    CynthError error = { 0 };
    for (; loop > 0; --loop) {
        error = cynth_engine_write_buffer(engine, &buffer, buffer.frame_amount);
        if (error != CYNTH_ERROR_NONE) {
            cynth_engine_deinit(engine);
            return 1;
        }
    }
    printf("Write ended.\n");

    printf("Draining.\n");
    error = cynth_engine_drain(engine);
    if (error != CYNTH_ERROR_NONE) {
        cynth_engine_deinit(engine);
        return 1;
    }

    printf("Drain ended.\n");
    printf("Arena used: %.2f KB / %.2f KB (%.2f%%)\n",
           varena.used / 1024.0f,
           varena.size / 1024.0f,
           100.0f * (float)varena.used / varena.size);

    cynth_engine_deinit(engine);
    return 0;
}
